/**
 * Bakes real elevation into the simulation grid of every region.
 *
 * Source: Copernicus DEM GLO-30 (© DLR e.V. 2010-2014 and © Airbus Defence and Space GmbH 2014-2018, provided under
 * COPERNICUS by the European Union and ESA; all rights reserved – free use licence). Read as cloud-optimised GeoTIFF
 * from the public AWS bucket; each 110 m cell is the mean of the ~30 m samples inside it.
 *
 * Output: src/data/elevation.generated.ts (base64, little-endian Int16 metres per cell). Run with `npm run bake:dem`.
 */
import { writeFileSync } from 'node:fs'
import { fromUrl } from 'geotiff'
import { REGIONS } from '../src/data/regions'
import { CELL_M, gridDims } from '../src/sim/terrain'
// only the areas named on the command line (e.g. `npm run bake:dem -- menderes`), merged into the existing file
const ONLY = process.argv.slice(2)
const AREAS = ONLY.length ? REGIONS.filter((r) => ONLY.includes(r.id)) : REGIONS


const BASE = 'https://copernicus-dem-30m.s3.amazonaws.com'
const tile = (lat: number, lon: number) => {
  const n = `Copernicus_DSM_COG_10_N${String(Math.floor(lat)).padStart(2, '0')}_00_E${String(Math.floor(lon)).padStart(3, '0')}_00_DEM`
  return `${BASE}/${n}/${n}.tif`
}

async function bake(region: (typeof REGIONS)[number]) {
  const { cols, rows } = gridDims(region.id)
  const n = cols * rows
  const dLat = CELL_M / 111320
  const dLon = CELL_M / (111320 * Math.cos((region.center[0] * Math.PI) / 180))
  const lat0 = region.center[0] + (rows * dLat) / 2
  const lon0 = region.center[1] - (cols * dLon) / 2
  const latS = lat0 - rows * dLat
  const lonE = lon0 + cols * dLon

  const sum = new Float64Array(n)
  const cnt = new Uint32Array(n)
  const tiles = new Set<string>()
  for (const la of [latS, lat0]) for (const lo of [lon0, lonE]) tiles.add(tile(la, lo))
  for (const url of tiles) {
    const img = await (await fromUrl(url)).getImage()
    const [ox, oy] = img.getOrigin()
    const [rx, ry] = img.getResolution()
    const px0 = Math.max(0, Math.floor((lon0 - ox) / rx))
    const px1 = Math.min(img.getWidth(), Math.ceil((lonE - ox) / rx))
    const py0 = Math.max(0, Math.floor((lat0 - oy) / ry))
    const py1 = Math.min(img.getHeight(), Math.ceil((latS - oy) / ry))
    if (px1 <= px0 || py1 <= py0) continue
    const [data] = (await img.readRasters({ window: [px0, py0, px1, py1] })) as unknown as Float32Array[]
    const w = px1 - px0
    for (let py = py0; py < py1; py++) {
      const row = Math.floor((lat0 - (oy + (py + 0.5) * ry)) / dLat)
      if (row < 0 || row >= rows) continue
      for (let px = px0; px < px1; px++) {
        const col = Math.floor((ox + (px + 0.5) * rx - lon0) / dLon)
        if (col < 0 || col >= cols) continue
        const v = data[(py - py0) * w + (px - px0)]
        if (!Number.isFinite(v) || v < -500) continue
        sum[row * cols + col] += v
        cnt[row * cols + col]++
      }
    }
  }
  const out = new Int16Array(n)
  let lo = Infinity
  let hi = -Infinity
  for (let i = 0; i < n; i++) {
    out[i] = cnt[i] ? Math.round(Math.max(0, sum[i] / cnt[i])) : 0
    lo = Math.min(lo, out[i])
    hi = Math.max(hi, out[i])
  }
  console.log(`  ${region.id}: ${tiles.size} tile(s), elevation ${lo}–${hi} m`)
  return Buffer.from(out.buffer).toString('base64')
}

const result: Record<string, string> = ONLY.length ? { ...(await import('../src/data/elevation.generated')).ELEVATION } : {}
for (const r of AREAS) {
  console.log(`baking ${r.id}`)
  result[r.id] = await bake(r)
}
writeFileSync(
  new URL('../src/data/elevation.generated.ts', import.meta.url),
  `// GENERATED by scripts/bake-dem.ts – do not edit.\n// Copernicus DEM GLO-30 (© DLR e.V. 2010-2014 and © Airbus Defence and Space GmbH 2014-2018, provided under COPERNICUS by the European Union and ESA).\n// Base64, little-endian Int16 metres per grid cell.\nexport const ELEVATION: Record<string, string> = {\n${Object.entries(result).map(([k, v]) => `  ${k}: '${v}',`).join('\n')}\n}\n`,
)
console.log('wrote src/data/elevation.generated.ts')
