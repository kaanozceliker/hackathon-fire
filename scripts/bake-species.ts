/**
 * Bakes the wild vertebrates recorded inside each region's grid from GBIF (https://www.gbif.org, occurrence data
 * under CC0 / CC BY / CC BY-NC per dataset; cite "GBIF.org occurrence data"). For each class it stores how many
 * species have records and the most recorded species with Turkish or English common name and IUCN category.
 *
 * Records show where species have been observed, not how many animals live there.
 * Output: src/data/species.generated.ts. Run with `npm run bake:species`.
 */
import { writeFileSync } from 'node:fs'
import { REGIONS } from '../src/data/regions'
import { getGrid } from '../src/sim/gridCache'
import { gridBounds } from '../src/sim/terrain'
import type { BakedSpeciesRegion, SpeciesClass } from '../src/data/speciesTypes'

const API = 'https://api.gbif.org/v1'
// GBIF's backbone splits reptiles into classes Squamata and Testudines.
const CLASSES: { key: SpeciesClass; gbif: number[] }[] = [
  { key: 'mammal', gbif: [359] },
  { key: 'bird', gbif: [212] },
  { key: 'reptile', gbif: [11592253, 11418114] },
  { key: 'amphibian', gbif: [131] },
]
/** Domestic and feral animals are not wildlife. */
const DOMESTIC = new Set(['Felis catus', 'Canis lupus', 'Canis familiaris', 'Bos taurus', 'Capra hircus', 'Ovis aries', 'Equus caballus', 'Equus asinus', 'Sus domesticus', 'Gallus gallus', 'Columba livia', 'Rattus norvegicus', 'Rattus rattus', 'Mus musculus'])
const TOP = 5

const get = async (url: string) => {
  for (let i = 0; i < 4; i++) {
    const r = await fetch(url, { headers: { 'User-Agent': 'forestguard-bake-script' } })
    if (r.ok) return r.json()
    await new Promise((res) => setTimeout(res, 2000 * (i + 1)))
  }
  throw new Error(`GBIF failed: ${url}`)
}

async function speciesInfo(key: string) {
  const sp = await get(`${API}/species/${key}`)
  const vern = await get(`${API}/species/${key}/vernacularNames?limit=200`).catch(() => ({ results: [] }))
  const pick = (lang: string) => (vern.results as any[]).find((v) => v.language === lang)?.vernacularName as string | undefined
  const iucn = await get(`${API}/species/${key}/iucnRedListCategory`).catch(() => null)
  return {
    scientific: (sp.canonicalName ?? sp.scientificName) as string,
    name: pick('tur') ?? pick('eng') ?? null,
    iucn: (iucn?.code as string | undefined) ?? null,
  }
}

const out: Record<string, BakedSpeciesRegion> = {}
for (const r of REGIONS) {
  const [[s, w], [n, e]] = gridBounds(getGrid(r.id))
  const poly = `POLYGON((${w} ${s},${e} ${s},${e} ${n},${w} ${n},${w} ${s}))`
  const classes: BakedSpeciesRegion['classes'] = []
  for (const c of CLASSES) {
    const q = `${API}/occurrence/search?geometry=${encodeURIComponent(poly)}&${c.gbif.map((k) => `classKey=${k}`).join('&')}&occurrenceStatus=PRESENT&facet=speciesKey&facetLimit=1000&limit=0`
    const res = await get(q)
    const counts: { name: string; count: number }[] = res.facets?.[0]?.counts ?? []
    const top = []
    let skipped = 0
    for (const f of counts) {
      if (top.length >= TOP) break
      const info = await speciesInfo(f.name)
      if (DOMESTIC.has(info.scientific)) { skipped++; continue }
      top.push({ ...info, records: f.count })
    }
    classes.push({ key: c.key, species: counts.length - skipped, records: res.count as number, top })
  }
  out[r.id] = { classes }
  console.log(`${r.id}: ${classes.map((c) => `${c.key} ${c.species} sp`).join(', ')}`)
}

writeFileSync(
  new URL('../src/data/species.generated.ts', import.meta.url),
  `// GENERATED by scripts/bake-species.ts – do not edit.\n// Species records: GBIF.org occurrence data (https://www.gbif.org), retrieved ${new Date().toISOString().slice(0, 10)}.\nimport type { BakedSpeciesRegion } from './speciesTypes'\n\nexport const SPECIES: Record<string, BakedSpeciesRegion> = ${JSON.stringify(out, null, 1)}\n`,
)
console.log('wrote src/data/species.generated.ts')
