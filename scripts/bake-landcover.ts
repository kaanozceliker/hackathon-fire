/**
 * Bakes real land cover into the simulation grid of every region.
 *
 * Source: ESA WorldCover 10 m 2021 v200 (© ESA WorldCover project 2021 / Contains modified Copernicus Sentinel data
 * (2021) processed by ESA WorldCover consortium, CC BY 4.0). Read as cloud-optimised GeoTIFF straight from the public
 * AWS bucket, so only the windows around each region are downloaded.
 *
 * For each 110 m grid cell the ~11×11 WorldCover pixels are counted and reduced to:
 *   kind  0 water, 1 built-up, 2 sparse / grass / crop / bare, 3 shrubland (maquis), 4 tree cover (forest)
 *   veg   vegetation density 0–255
 *
 * Output: src/data/landcover.generated.ts (base64, two bytes per cell). Run with `npm run bake:landcover`.
 */
import { writeFileSync } from 'node:fs'
import { fromUrl } from 'geotiff'
import { REGIONS } from '../src/data/regions'
import { CELL_M, gridDims } from '../src/sim/terrain'
// only the areas named on the command line (e.g. `npm run bake:landcover -- menderes`), merged into the existing file
const ONLY = process.argv.slice(2)
const AREAS = ONLY.length ? REGIONS.filter((r) => ONLY.includes(r.id)) : REGIONS


const BASE = 'https://esa-worldcover.s3.eu-central-1.amazonaws.com/v200/2021/map'
const tileName = (lat: number, lon: number) => {
  const s = Math.floor(lat / 3) * 3
  const w = Math.floor(lon / 3) * 3
  return `ESA_WorldCover_10m_2021_v200_N${String(s).padStart(2, '0')}E${String(w).padStart(3, '0')}_Map.tif`
}

// WorldCover class code -> histogram slot
const SLOT: Record<number, number> = { 10: 1, 20: 2, 30: 3, 40: 4, 50: 5, 60: 6, 70: 6, 80: 7, 90: 8, 95: 1, 100: 6 }
const NSLOT = 9 // 0 = no data

async function bake(region: (typeof REGIONS)[number]) {
  const { cols, rows } = gridDims(region.id)
  const n = cols * rows
  const dLat = CELL_M / 111320
  const dLon = CELL_M / (111320 * Math.cos((region.center[0] * Math.PI) / 180))
  const lat0 = region.center[0] + (rows * dLat) / 2
  const lon0 = region.center[1] - (cols * dLon) / 2
  const latS = lat0 - rows * dLat
  const lonE = lon0 + cols * dLon

  const hist = new Uint32Array(n * NSLOT)
  const tiles = new Set<string>()
  for (const la of [latS, lat0]) for (const lo of [lon0, lonE]) tiles.add(tileName(la, lo))

  for (const t of tiles) {
    const tiff = await fromUrl(`${BASE}/${t}`)
    const img = await tiff.getImage()
    const [ox, oy] = img.getOrigin()
    const [rx, ry] = img.getResolution() // ry is negative
    const W = img.getWidth()
    const H = img.getHeight()
    const px0 = Math.max(0, Math.floor((lon0 - ox) / rx))
    const px1 = Math.min(W, Math.ceil((lonE - ox) / rx))
    const py0 = Math.max(0, Math.floor((lat0 - oy) / ry))
    const py1 = Math.min(H, Math.ceil((latS - oy) / ry))
    if (px1 <= px0 || py1 <= py0) continue
    const [data] = (await img.readRasters({ window: [px0, py0, px1, py1] })) as unknown as Uint8Array[]
    const w = px1 - px0
    for (let py = py0; py < py1; py++) {
      const lat = oy + (py + 0.5) * ry
      const row = Math.floor((lat0 - lat) / dLat)
      if (row < 0 || row >= rows) continue
      for (let px = px0; px < px1; px++) {
        const lon = ox + (px + 0.5) * rx
        const col = Math.floor((lon - lon0) / dLon)
        if (col < 0 || col >= cols) continue
        hist[(row * cols + col) * NSLOT + (SLOT[data[(py - py0) * w + (px - px0)]] ?? 0)]++
      }
    }
    console.log(`  ${region.id}: read ${t} window ${w}×${py1 - py0}`)
  }

  const out = new Uint8Array(n * 2)
  const counts = [0, 0, 0, 0, 0]
  for (let i = 0; i < n; i++) {
    const h = hist.subarray(i * NSLOT, i * NSLOT + NSLOT)
    const total = h.reduce((a, b) => a + b, 0)
    let kind: number
    let veg = 0
    // No data inside the tile means open sea.
    const water = total === 0 ? 1 : (h[7] + h[0]) / total
    const land = total - h[7] - h[0]
    if (water >= 0.5 || land <= 0) kind = 0
    else {
      const f = (s: number) => h[s] / land
      veg = f(1) * 1 + f(2) * 0.7 + f(3) * 0.4 + f(4) * 0.22 + f(8) * 0.15 + f(6) * 0.03
      if (f(5) >= 0.35) kind = 1
      else if (f(1) >= 0.4) kind = 4
      else if (f(1) + f(2) >= 0.4) kind = 3
      else kind = 2
    }
    counts[kind]++
    out[i * 2] = kind
    out[i * 2 + 1] = Math.round(Math.min(1, Math.max(0, veg)) * 255)
  }
  console.log(`  ${region.id}: water ${counts[0]}, built ${counts[1]}, sparse ${counts[2]}, shrub ${counts[3]}, forest ${counts[4]}`)
  return Buffer.from(out).toString('base64')
}

const result: Record<string, string> = ONLY.length ? { ...(await import('../src/data/landcover.generated')).LANDCOVER } : {}
for (const r of AREAS) {
  console.log(`baking ${r.id}`)
  result[r.id] = await bake(r)
}

const body = Object.entries(result)
  .map(([k, v]) => `  ${k}: '${v}',`)
  .join('\n')
writeFileSync(
  new URL('../src/data/landcover.generated.ts', import.meta.url),
  `// GENERATED by scripts/bake-landcover.ts – do not edit.\n// Land cover from ESA WorldCover 10 m 2021 v200 (© ESA WorldCover project / Copernicus Sentinel data, CC BY 4.0).\n// Base64, two bytes per grid cell: kind (0 water, 1 built-up, 2 sparse, 3 shrubland, 4 forest), vegetation density 0–255.\nexport const LANDCOVER: Record<string, string> = {\n${body}\n}\n`,
)
console.log('wrote src/data/landcover.generated.ts')
